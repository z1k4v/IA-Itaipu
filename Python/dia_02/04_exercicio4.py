# Faça um prograna que receba um número inteiro e calcule sua raiz quadrada e exiba o resultado.

print("Vamos aprender a calcular a raiz quadrada?")

numero = input("Insira aqui o número desejado para calcular a raiz quadrada. (Esse número deve ser inserido em algarismo numérico inteiro. ex.: 144)")

raiz_quadrada = int(numero) ** (1 / 2)

print("A raiz quadrada de", numero, "é", raiz_quadrada)